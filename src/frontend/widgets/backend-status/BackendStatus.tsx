"use client"; // Компонент должен выполняться в браузере

import { useEffect, useState } from "react";

// Переменная этого типа может содержать только одно из трёх значений: "checking", "healthy" или "unhealthy".
type BackendStatusState = 
    | "checking"
    | "healthy"
    | "unhealthy";

// Это React-компонент, который вызывается
// 1. когда страница впервые отображается
// 2. когда меняется его state (например, когда мы вызываем setStatus)
// 3. когад меняются его props (в данном случае props нет). props - это объект, который содержит все свойства, переданные компоненту. 
export function BackendStatus() {
    // const [status, setStatus] - это деструктуризация массива, возвращаемого useState. Деструктуризация - это способ извлечь значения из массивов или объектов и присвоить их переменным.
    // Диструктуризация тут используется для того, чтобы получить текущее состояние (status) и функцию для его обновления (setStatus) из хука useState.
    // Изначально диструктуризация присваивает status значение "checking", что означает, что мы пока проверяем состояние бэкэнда.
    // При смене состояния с помощью setStatus, React повторно рендерит компонент с новым значением status, что позволяет отображать актуальное состояние бэкэнда пользователю.
    // useState - это хук, который позволяет компоненту хранить состояние
    // хук - это функция, которая позволяет "подключиться" к функционалу React из функционального компонента
    const [status, setStatus] = useState<BackendStatusState>("checking");

    // Запускает код после отображения компонента в браузере. Проверяет состояние бэкэнда.
    useEffect(() => {
        async function checkBackend() {
            try {
                const response = await fetch("/api/health"); // делает HTTP-запрос к backend endpoint

                setStatus(response.ok ? "healthy" : "unhealthy");
            } catch {
                setStatus("unhealthy");
            }
        }

        checkBackend();
    }, []); // Пустой массив зависимостей означает, что эффект выполняется только один раз после монтирования компонента (первой загрузки страницы)

    if (status === "checking") {
        return <p>Проверяем backend...</p>;
    }

    if (status === "healthy") {
        return <p>Бэкэнд жив</p>;
    }

    return <p>Бэкэнд не работает</p>;
}